"""Build a compact inventory of locally available experiment artifacts."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--results-dir", default="results")
    parser.add_argument("--output", default="results/summary/artifact_inventory.md")
    return parser.parse_args()


def read_manifest(path: Path) -> dict:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}


def csv_shape(path: Path) -> tuple[int, int] | None:
    try:
        frame = pd.read_csv(path, nrows=0)
        rows = sum(1 for _ in path.open(encoding="utf-8")) - 1
        return max(rows, 0), len(frame.columns)
    except (OSError, UnicodeDecodeError, pd.errors.ParserError):
        return None


def main() -> None:
    args = parse_args()
    root = Path(args.results_dir)
    manifests = sorted(root.rglob("run_manifest.json"))
    csvs = sorted(root.glob("summary/*.csv")) + sorted(root.glob("analysis/*.csv"))

    lines = ["# Local artifact inventory", "", "Generated by `scripts/summarize_artifacts.py`.", ""]
    lines += ["## Completed runs", "", "| Run | Model | Status | Prompt file |", "|---|---|---|---|"]
    for path in manifests:
        manifest = read_manifest(path)
        lines.append(
            f"| `{path.parent}` | `{manifest.get('model_id') or manifest.get('model') or 'unknown'}` "
            f"| `{manifest.get('status', 'unknown')}` | `{manifest.get('prompt_file') or 'unknown'}` |"
        )
    if not manifests:
        lines.append("| *(none found)* | | | |")

    lines += ["", "## Summary tables", "", "| File | Rows | Columns |", "|---|---:|---:|"]
    for path in csvs:
        shape = csv_shape(path)
        if shape is None:
            continue
        lines.append(f"| `{path}` | {shape[0]} | {shape[1]} |")
    if not csvs:
        lines.append("| *(none found)* | | |")

    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {output}")


if __name__ == "__main__":
    main()
